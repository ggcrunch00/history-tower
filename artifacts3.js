// 세로로 세운 종이(가운데 x, 바닥 y, 가로 w, 세로 h)에 세로쓰기 글줄 n개
function paperLines(m, x, y, w, h, n, ink = "#2a2420", z = 0.12) {
  for (let k = 0; k < n; k++) m.b(0.1, h * 0.8, 0.04, ink, x + w / 2 - w / (n + 1) * (k + 1), y + h * 0.1, z);
}
// 작은 태극기 판 (가운데 x, 바닥 y, z, 가로 w)
function flagBoard(m, x, y, z, w) {
  const h = w * 2 / 3;
  m.b(w, h, 0.08, "#ffffff", x, y, z);
  const r = h * 0.25;
  m.cyl(r, r, 0.05, "#cd2e3a", x, y + h / 2, z + 0.06, 16, Math.PI / 2);
  for (let i = 0; i < 6; i++) {   // 태극 아래쪽 파랑: 반원을 가로 띠로 채움
    const dy = (i + 0.5) * r / 6, w = 2 * Math.sqrt(r * r - dy * dy);
    m.box(w, r / 6 + 0.01, 0.05, "#0047a0", x, y + h / 2 - dy, z + 0.07);
  }
  [[-1, 1], [1, 1], [-1, -1], [1, -1]].forEach(([sx, sy]) => m.box(w * 0.14, h * 0.14, 0.05, "#1a1a1a", x + sx * w * 0.33, y + h / 2 + sy * h * 0.3, z + 0.06, 0, 0, sx * sy * 0.6));
}

