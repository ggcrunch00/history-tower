// 세워 둔 책의 한쪽 면(가운데 cx, 비스듬히 ry만큼 돌림) 위에 무늬 붙이기. lx: 면 위 가로 위치, y: 높이
function pageDecor(m, cx, cz, ry, lx, y, w, h, color) {
  const n = 0.1;
  m.box(w, h, 0.04, color, cx + lx * Math.cos(ry) + n * Math.sin(ry), y, cz - lx * Math.sin(ry) + n * Math.cos(ry), ry);
}
// 펼쳐서 세워 둔 책: 왼쪽·오른쪽 면을 안쪽으로 조금 접음. 면마다 (m, 가운데x, 가운데z, 회전) 로 무늬를 그림
function openBook(m, cover, paper, left, right) {
  [[-1.5, 0.3, left], [1.5, -0.3, right]].forEach(([cx, ry, draw]) => {
    m.b(3.2, 4.7, 0.15, cover, cx, 0, -0.05, ry);
    m.b(3.0, 4.5, 0.15, paper, cx, 0.1, 0.08, ry);
    draw(cx, 0.08, ry);
  });
  m.b(0.25, 4.6, 0.5, cover, 0, 0, -0.35);
}
// 기와지붕 (아래에서 위로 좁아짐)
function tileRoof(m, x, y, z, w, d, color = "#4a4f57", color2 = "#555a62") {
  m.b(w, 0.45, d, color, x, y, z);
  m.b(w - 1, 0.45, d - 1, color2, x, y + 0.45, z);
  m.b(w - 2.2, 0.45, Math.max(0.8, d - 2.2), color, x, y + 0.9, z);
  m.b(w - 1.6, 0.35, 0.45, "#3a3f47", x, y + 1.35, z);
}

