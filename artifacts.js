// 회전체 윤곽선에서 높이 y의 반지름 구하기 (무늬를 표면에 붙일 때 사용)
function profileRadius(profile, y) {
  for (let i = 0; i < profile.length - 1; i++) {
    const [r0, y0] = profile[i], [r1, y1] = profile[i + 1];
    if (y >= y0 && y <= y1) return y1 === y0 ? r1 : r0 + (r1 - r0) * (y - y0) / (y1 - y0);
  }
  return profile[profile.length - 1][0];
}
// 둘레를 따라 표면에 작은 장식 붙이기
function ringDecor(m, profile, y, count, w, h, color, offset = 0) {
  const r = profileRadius(profile, y) + 0.03;
  for (let k = 0; k < count; k++) {
    const a = offset + (k / count) * Math.PI * 2;
    m.box(w, h, 0.08, color, Math.cos(a) * r, y, Math.sin(a) * r, Math.PI / 2 - a);
  }
}

